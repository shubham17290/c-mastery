//  Programs that can teach you the --> relational operators more than anyone else

#include <stdio.h>

int main() {
    printf("Lets see their integer output of the expression\n");

    printf("%d\n", 10 < 20);  // result = true = 1
    printf("%d\n", 10 > 20);  // result = false = 0
    printf("%d\n", 10 < 3);   // result = false = 0
    printf("%d\n", 10 > 3);   // result = true = 1
    printf("%d\n", 10 <= 20); // result = true = 1
    printf("%d\n", 10 >= 20); // result = false = 0
    printf("%d\n", 1 >= 6);   // result = false = 0
    printf("%d\n", 6 <= 6);   // result = true = 1
    printf("%d\n", 10 == 10); // result = true = 1
    printf("%d\n", 10 != 20); // result = true = 1
    printf("%d\n", 2 != 2);   // result = false = 0

    printf("Lets see their character output \n");

    printf("%c\n", 10 < 20);  // result = true = 1
    printf("%c\n", 10 > 20);  // result = false = 0
    printf("%c\n", 10 < 3);   // result = false = 0
    printf("%c\n", 10 > 3);   // result = true = 1
    printf("%c\n", 10 <= 20); // result = true = 1
    printf("%c\n", 10 >= 20); // result = false = 0
    printf("%d\n", 1 >= 6);   // result = false = 0
    printf("%c\n", 6 <= 6);   // result = true = 1
    printf("%c\n", 10 == 10); // result = true = 1
    printf("%c\n", 10 != 20); // result = true = 1
    printf("%c\n", 2 != 2);   // result = false = 0

    return 0;
}
